-- ProductVariant -> Product.total_stock (stock of active variants).
CREATE OR REPLACE FUNCTION trg_variant_total_stock() RETURNS trigger AS $$
BEGIN
  IF TG_OP IN ('UPDATE', 'DELETE') THEN
    UPDATE "Product" SET total_stock = GREATEST(0, total_stock - (CASE WHEN OLD.is_active THEN OLD.stock ELSE 0 END))
    WHERE id = OLD.product_id;
  END IF;
  IF TG_OP IN ('INSERT', 'UPDATE') THEN
    UPDATE "Product" SET total_stock = total_stock + (CASE WHEN NEW.is_active THEN NEW.stock ELSE 0 END)
    WHERE id = NEW.product_id;
  END IF;
  RETURN NULL;
END $$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_variant_total_stock ON "ProductVariant";
CREATE TRIGGER trg_variant_total_stock
  AFTER INSERT OR DELETE OR UPDATE OF stock, is_active, product_id ON "ProductVariant"
  FOR EACH ROW EXECUTE FUNCTION trg_variant_total_stock();

-- Notification -> Profile.unread_notification_count.
CREATE OR REPLACE FUNCTION trg_notification_unread() RETURNS trigger AS $$
BEGIN
  IF TG_OP = 'UPDATE' AND OLD.is_read = NEW.is_read AND OLD.user_id = NEW.user_id THEN
    RETURN NULL;
  END IF;
  IF TG_OP IN ('UPDATE', 'DELETE') AND NOT OLD.is_read THEN
    UPDATE "Profile" SET unread_notification_count = GREATEST(0, unread_notification_count - 1) WHERE id = OLD.user_id;
  END IF;
  IF TG_OP IN ('INSERT', 'UPDATE') AND NOT NEW.is_read THEN
    UPDATE "Profile" SET unread_notification_count = unread_notification_count + 1 WHERE id = NEW.user_id;
  END IF;
  RETURN NULL;
END $$ LANGUAGE plpgsql;

