    RETURN NULL;
  END IF;
  IF TG_OP IN ('UPDATE', 'DELETE') AND NOT OLD.is_archived AND OLD.club_id IS NOT NULL THEN
    UPDATE "Club" SET product_count = GREATEST(0, product_count - 1) WHERE id = OLD.club_id;
  END IF;
  IF TG_OP IN ('INSERT', 'UPDATE') AND NOT NEW.is_archived AND NEW.club_id IS NOT NULL THEN
    UPDATE "Club" SET product_count = product_count + 1 WHERE id = NEW.club_id;
  END IF;
  RETURN NULL;
