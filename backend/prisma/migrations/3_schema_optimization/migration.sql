-- 4. Backfill the stored counters from the source rows ---------------------------------------------
UPDATE "Event" e SET
  pending_count   = c.p,
  confirmed_count = c.c,
  rejected_count  = c.r
FROM (
  SELECT event_id,
         count(*) FILTER (WHERE status = 'PENDING')   AS p,
         count(*) FILTER (WHERE status = 'CONFIRMED') AS c,
         count(*) FILTER (WHERE status = 'REJECTED')  AS r
  FROM "Registration" GROUP BY event_id
) c WHERE c.event_id = e.id;

UPDATE "Team" t SET member_count = c.n
FROM (
  SELECT team_id, count(*) AS n FROM "Registration"
  WHERE team_id IS NOT NULL AND status IN ('PENDING', 'CONFIRMED') GROUP BY team_id
) c WHERE c.team_id = t.id;

UPDATE "Registration" r SET club_id = e.club_id FROM "Event" e WHERE e.id = r.event_id AND r.club_id IS NULL;

UPDATE "Club" c SET
  event_count   = (SELECT count(*) FROM "Event"   e WHERE e.club_id = c.id AND NOT e.is_archived),
  product_count = (SELECT count(*) FROM "Product" p WHERE p.club_id = c.id AND NOT p.is_archived);

UPDATE "Product" p SET total_stock =
  COALESCE((SELECT sum(v.stock) FROM "ProductVariant" v WHERE v.product_id = p.id AND v.is_active), 0);

UPDATE "Profile" p SET unread_notification_count =
  (SELECT count(*) FROM "Notification" n WHERE n.user_id = p.id AND NOT n.is_read);


-- 5. Triggers that keep the counters correct --------------------------------------------------------
-- Counters change by deltas (x = x + 1), never by re-counting, so concurrent writers cannot overwrite
-- each other. GREATEST(0, ...) keeps a counter from going negative if it was ever out of step;
-- `npm run db:verify-counters` recomputes every counter and reports (or fixes) any drift.

-- Registration: copy the event's club on insert.
CREATE OR REPLACE FUNCTION trg_registration_club() RETURNS trigger AS $$
BEGIN
  IF NEW.club_id IS NULL THEN
    SELECT club_id INTO NEW.club_id FROM "Event" WHERE id = NEW.event_id;
  END IF;
  RETURN NEW;
END $$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_registration_club ON "Registration";
CREATE TRIGGER trg_registration_club BEFORE INSERT ON "Registration"
  FOR EACH ROW EXECUTE FUNCTION trg_registration_club();

-- Registration: per-status event counters and team member count.
CREATE OR REPLACE FUNCTION trg_registration_counts() RETURNS trigger AS $$
BEGIN
  IF TG_OP = 'UPDATE'
     AND OLD.status = NEW.status AND OLD.event_id = NEW.event_id
     AND OLD.team_id IS NOT DISTINCT FROM NEW.team_id THEN
    RETURN NULL;
  END IF;

  IF TG_OP IN ('UPDATE', 'DELETE') THEN
    UPDATE "Event" SET
      pending_count   = GREATEST(0, pending_count   - (OLD.status = 'PENDING')::int),
      confirmed_count = GREATEST(0, confirmed_count - (OLD.status = 'CONFIRMED')::int),
      rejected_count  = GREATEST(0, rejected_count  - (OLD.status = 'REJECTED')::int)
    WHERE id = OLD.event_id;
    IF OLD.team_id IS NOT NULL AND OLD.status IN ('PENDING', 'CONFIRMED') THEN
      UPDATE "Team" SET member_count = GREATEST(0, member_count - 1) WHERE id = OLD.team_id;
    END IF;
  END IF;

  IF TG_OP IN ('INSERT', 'UPDATE') THEN
    UPDATE "Event" SET
      pending_count   = pending_count   + (NEW.status = 'PENDING')::int,
      confirmed_count = confirmed_count + (NEW.status = 'CONFIRMED')::int,
      rejected_count  = rejected_count  + (NEW.status = 'REJECTED')::int
    WHERE id = NEW.event_id;
    IF NEW.team_id IS NOT NULL AND NEW.status IN ('PENDING', 'CONFIRMED') THEN
      UPDATE "Team" SET member_count = member_count + 1 WHERE id = NEW.team_id;
    END IF;
  END IF;
  RETURN NULL;
END $$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_registration_counts ON "Registration";
CREATE TRIGGER trg_registration_counts
  AFTER INSERT OR DELETE OR UPDATE OF status, event_id, team_id ON "Registration"
  FOR EACH ROW EXECUTE FUNCTION trg_registration_counts();

-- Event -> Club.event_count (non-archived events).
CREATE OR REPLACE FUNCTION trg_event_club_count() RETURNS trigger AS $$
BEGIN
  IF TG_OP = 'UPDATE' AND OLD.is_archived = NEW.is_archived AND OLD.club_id = NEW.club_id THEN
    RETURN NULL;
  END IF;
  IF TG_OP IN ('UPDATE', 'DELETE') AND NOT OLD.is_archived THEN
    UPDATE "Club" SET event_count = GREATEST(0, event_count - 1) WHERE id = OLD.club_id;
  END IF;
  IF TG_OP IN ('INSERT', 'UPDATE') AND NOT NEW.is_archived THEN
    UPDATE "Club" SET event_count = event_count + 1 WHERE id = NEW.club_id;
  END IF;
  RETURN NULL;
END $$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_event_club_count ON "Event";
CREATE TRIGGER trg_event_club_count
  AFTER INSERT OR DELETE OR UPDATE OF is_archived, club_id ON "Event"
  FOR EACH ROW EXECUTE FUNCTION trg_event_club_count();

-- Product -> Club.product_count (non-archived products; club may be NULL).
